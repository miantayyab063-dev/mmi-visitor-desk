CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL,
 password_hash VARCHAR(255) NOT NULL, active TINYINT NOT NULL DEFAULT 1,
 auth_version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS visitors (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 mobile VARCHAR(18) CHARACTER SET ascii NOT NULL UNIQUE,
 cnic VARCHAR(13) CHARACTER SET ascii NOT NULL UNIQUE,
 version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS visits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 visitor_id BIGINT UNSIGNED NOT NULL,
 at VARCHAR(25) NOT NULL, out_at VARCHAR(25) NULL,
 host VARCHAR(150) NOT NULL DEFAULT '', purpose TEXT NOT NULL, remarks TEXT NOT NULL,
 staff VARCHAR(40) NOT NULL, out_by VARCHAR(40) NOT NULL DEFAULT '',
 updated_at VARCHAR(25) NULL, updated_by VARCHAR(40) NOT NULL DEFAULT '',
 version INT NOT NULL DEFAULT 1,
 snapshot_name VARCHAR(100) NOT NULL, snapshot_mobile VARCHAR(18) NOT NULL,
 snapshot_cnic VARCHAR(13) NOT NULL,
 token VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 INDEX person_at(visitor_id,at), INDEX visit_time(at), INDEX visit_open(out_at,visitor_id),
 CONSTRAINT visits_visitor_fk FOREIGN KEY(visitor_id) REFERENCES visitors(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS calls (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 phone VARCHAR(18) CHARACTER SET ascii NOT NULL, caller VARCHAR(100) NOT NULL DEFAULT '',
 at VARCHAR(25) NOT NULL, duration INT UNSIGNED NOT NULL,
 remarks TEXT NOT NULL, spoken_by VARCHAR(100) NOT NULL, kind VARCHAR(20) NOT NULL,
 created_at VARCHAR(25) NOT NULL, staff VARCHAR(40) NOT NULL,
 token VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 version INT NOT NULL DEFAULT 1, updated_at VARCHAR(25) NULL,
 updated_by VARCHAR(40) NOT NULL DEFAULT '', INDEX calls_phone(phone,id), INDEX calls_time(at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS sessions_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, username VARCHAR(40) NOT NULL,
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 auth_version INT NOT NULL, login_at VARCHAR(25) NOT NULL,
 logout_at VARCHAR(25) NULL, last_seen VARCHAR(25) NULL, end_reason VARCHAR(100) NULL,
 expires BIGINT NOT NULL, activity BIGINT NOT NULL,
 INDEX user_sessions(user_id,id), INDEX session_user(username,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS change_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 at VARCHAR(25) NOT NULL, staff VARCHAR(40) NOT NULL,
 action VARCHAR(600) NOT NULL, entity VARCHAR(30) NOT NULL, record_id BIGINT UNSIGNED NOT NULL,
 before_json LONGTEXT NULL, after_json LONGTEXT NULL,
 INDEX entity_record(entity,record_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(100) CHARACTER SET ascii PRIMARY KEY, value LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS login_attempts (
 attempt_key CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 failures INT NOT NULL DEFAULT 0, window_start BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
